import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const run = (command, args) => {
  const result = spawnSync(command, args, {
    cwd: new URL("..", import.meta.url),
    encoding: "utf8",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed:\n${result.stderr}`);
  }
  return result.stdout;
};

const tempDir = mkdtempSync(join(tmpdir(), "lingostack-notices-"));
const rustNoticePath = join(tempDir, "rust-notices.md");
try {
  run("cargo", [
    "about",
    "generate",
    "--workspace",
    "--output-file",
    rustNoticePath,
    "licenses/rust-notices.hbs",
  ]);
  const rust = readFileSync(rustNoticePath, "utf8").trimEnd();
  const rawFrontend =
    process.platform === "win32"
      ? run(process.env.ComSpec ?? "cmd.exe", [
          "/d",
          "/s",
          "/c",
          "pnpm licenses list --json --prod",
        ])
      : run("pnpm", ["licenses", "list", "--json", "--prod"]);
  const frontendByLicense = JSON.parse(rawFrontend);
  const frontend = Object.entries(frontendByLicense)
    .flatMap(([license, packages]) =>
      packages.flatMap((pkg) =>
        pkg.versions.map((version) => ({
          license,
          name: pkg.name,
          version,
          homepage: pkg.homepage ?? "",
        })),
      ),
    )
    .sort(
      (a, b) =>
        a.license.localeCompare(b.license) ||
        a.name.localeCompare(b.name) ||
        a.version.localeCompare(b.version),
    );

  const lines = [
    "# Third-party notices",
    "",
    "Generated by `pnpm notices:generate`; do not edit manually.",
    "",
    "## Frontend production dependencies",
    "",
    "| Package | Version | SPDX license | Homepage |",
    "| --- | --- | --- | --- |",
    ...frontend.map(
      ({ name, version, license, homepage }) =>
        `| ${name} | ${version} | ${license} | ${homepage} |`,
    ),
    "",
    rust,
    "",
  ];
  writeFileSync(
    new URL("../THIRD_PARTY_NOTICES", import.meta.url),
    lines.join("\n"),
  );
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
